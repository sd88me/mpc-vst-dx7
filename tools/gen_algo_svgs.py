BOX_W, BOX_H = 16, 12
ACCENT, INK, FILL = "#009caf", "#d8dee2", "#0b0d0e"
VIEW_W, VIEW_H = 900, 470


def lines(x, y, link, fb):
    """Line segments (x1, y1, x2, y2) for one operator, from Dexed's displayOp switch."""
    L = []
    if link == 0:
        L += [(x+8, y+12, x+8, y+21)]
    elif link == 1:
        L += [(x+8, y+12, x+8, y+18), (x+8, y+18, x+34, y+18)]
    elif link == 2:
        L += [(x+8, y+12, x+8, y+19)]
    elif link == 3:
        L += [(x+8, y+12, x+8, y+21), (x+8, y+18, x+34, y+18), (x+34, y+18, x+34, y+21)]
    elif link == 4:
        L += [(x+8, y+12, x+8, y+21), (x+8, y+18, x+34, y+18), (x+34, y+18, x+34, y+21),
              (x-17, y+18, x+8, y+18), (x-17, y+18, x-17, y+21)]
    elif link == 6:
        L += [(x+8, y+12, x+8, y+18), (x+8, y+18, x+58, y+18)]
    elif link == 7:
        L += [(x+8, y+12, x+8, y+19), (x-17, y+18, x+8, y+18)]
    if fb == 1:
        L += [(x+8, y, x+8, y-4), (x+8, y-4, x+20, y-4), (x+20, y-4, x+20, y+15), (x+20, y+15, x+8, y+15)]
    elif fb == 2:
        L += [(x+8, y, x+8, y-4), (x+8, y-4, x+19, y-4), (x+19, y-4, x+19, y+58), (x+19, y+58, x+8, y+58)]
    elif fb == 3:
        L += [(x+8, y, x+8, y-4), (x+8, y-4, x+19, y-4), (x+19, y-4, x+19, y+36), (x+19, y+36, x+8, y+36)]
    elif fb == 4:
        L += [(x+8, y, x+8, y-4), (x+8, y-4, x-3, y-4), (x-3, y-4, x-3, y+15), (x-3, y+15, x+8, y+15),
              (x+8, y+15, x+8, y+12)]
    return L


def svg(ops):
    segs, boxes = [], []
    for op, col, row, link, fb in ops:
        x, y = col * 25 + 3, row * 21 + 5
        segs += lines(x, y, link, fb)
        boxes.append((op, x, y))
    xs = [v for s in segs for v in (s[0], s[2])] + [b[1] for b in boxes] + [b[1] + BOX_W for b in boxes]
    ys = [v for s in segs for v in (s[1], s[3])] + [b[2] for b in boxes] + [b[2] + BOX_H for b in boxes]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    k = min(VIEW_W / (x1 - x0 + 16), VIEW_H / (y1 - y0 + 16))
    ox = (VIEW_W - k * (x1 - x0)) / 2 - k * x0
    oy = (VIEW_H - k * (y1 - y0)) / 2 - k * y0
    o = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">' % (VIEW_W, VIEW_H, VIEW_W, VIEW_H),
         '<g transform="translate(%.2f %.2f) scale(%.3f)" stroke-linecap="square" stroke-linejoin="miter">' % (ox, oy, k),
         '<g stroke="%s" stroke-width="1.1" fill="none">' % ACCENT]
    o += ['<line x1="%g" y1="%g" x2="%g" y2="%g"/>' % s for s in segs]
    o.append('</g>')
    for op, x, y in boxes:
        o.append('<rect x="%g" y="%g" width="%d" height="%d" rx="1.5" fill="%s" stroke="%s" stroke-width="0.9"/>' % (x, y, BOX_W, BOX_H, FILL, ACCENT))
        o.append('<text x="%g" y="%g" font-family="Titillium Web, Helvetica, Arial, sans-serif" font-size="9" font-weight="700" '
                 'text-anchor="middle" fill="%s">%d</text>' % (x + BOX_W / 2, y + 9, INK, op))
    o.append('</g></svg>')
    return "\n".join(o) + "\n"


