#!/usr/bin/env python3
"""Generate src/params_gen.h: the 2.0 plugin's parameter table, from module.json, in params.lock order.

params.lock is the frozen order from 1.x (parameter index = VST parameter number), so existing projects and
skins keep binding to the same indices. A key in params.lock that module.json lacks is an error; a key in
module.json that params.lock lacks must be appended to params.lock (last) first.

    python3 tools/gen_params.py
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def specs():
    m = json.load(open(os.path.join(ROOT, "module.json")))
    out = {}

    def walk(o):
        if isinstance(o, dict):
            if "key" in o and ("min" in o or "options" in o):
                out[o["key"]] = o
                return
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)
    walk(m)
    return out


def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    sp = specs()
    lock = [l.strip() for l in open(os.path.join(ROOT, "params.lock")) if l.strip()]
    missing = [k for k in lock if k not in sp]
    extra = [k for k in sp if k not in lock]
    if missing or extra:
        sys.exit("params.lock / module.json mismatch: missing %s, unlocked %s" % (missing, extra))
    rows = []
    for k in lock:
        s = sp[k]
        name = s.get("name", k)[:24]
        write = s.get("access") == "write"
        string = s.get("display") == "string"
        if "options" in s:
            kind = "Choice"
            lo, hi = 0, len(s["options"]) - 1
            choices = "{" + ", ".join(c(o) for o in s["options"]) + "}"
        else:
            kind = "Int"
            lo, hi = s["min"], s["max"]
            if hi <= lo:
                hi = lo + 1        # read-only text params (bank_page_text): give the host a non-empty range
            choices = "{}"
        d = s.get("default", 0)
        flags = []
        if write:
            flags.append("kMomentary")
        if string:
            flags.append("kText")
        rows.append('    {%s, %s, ParamSpec::%s, %d, %d, %d, %s, %s},' % (
            c(k), c(name), kind, lo, hi, d, " | ".join(flags) or "0", choices))
    hdr = ("/* generated by tools/gen_params.py from module.json in params.lock order: do not edit */\n"
           "#pragma once\n#include <vector>\n#include <string>\n\n"
           "enum ParamFlags { kMomentary = 1, kText = 2 };\n"
           "struct ParamSpec {\n    enum Kind { Int, Choice };\n    const char* key; const char* name; Kind kind;\n"
           "    int min, max, def; int flags; std::vector<std::string> choices;\n};\n\n"
           "// Built once and never freed: no static destructor runs when the MPC unloads the library.\n"
           "static const std::vector<ParamSpec>& paramSpecs() {\n    static const std::vector<ParamSpec>& t = *new std::vector<ParamSpec>{\n"
           + "\n".join(rows) + "\n    };\n    return t;\n}\n")
    open(os.path.join(ROOT, "src", "params_gen.h"), "w").write(hdr)
    print("src/params_gen.h: %d params" % len(rows))


if __name__ == "__main__":
    main()
